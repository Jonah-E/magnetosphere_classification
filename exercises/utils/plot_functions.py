spedas_cmap = colors.LinearSegmentedColormap.from_list('spedas', _colors)


# ── spectrum_plot ────────────────────────────────────────────────────────────
def spectrum_plot(time, energy, flux, ax=None, c_norm='log', cmap='spedas',
                  zlim=None, c_bar=True, labels=True, y_scale='log'):
    """
    Plot an energy-time spectrogram.

    Parameters
    ----------
    time   : 1-D array of datetime64 or numeric, length N
    energy : 1-D array of energy bin centres, length M
    flux   : 2-D array (N, M)
    ax     : existing Axes, or None to create one
    """
    if ax is None:
        fig, ax = plt.subplots(1, 1)
    else:
        fig = ax.get_figure()

    T, E = np.meshgrid(time, energy)
    Z = flux.T.copy()

    vmin, vmax = np.nanmin(Z), np.nanmax(Z)
    if zlim is not None:
        vmin, vmax = zlim

    if c_norm == 'log':
        Z[Z <= 0] = np.nan
        vmin = np.nanmin(Z) if zlim is None else zlim[0]
        vmax = np.nanmax(Z) if zlim is None else zlim[1]
        norm = LogNorm(vmin=vmin, vmax=vmax)
    elif c_norm == 'symlog':
        norm = SymLogNorm(linthresh=1e-2, linscale=1, base=10,
                          vmin=vmin, vmax=vmax)
    else:
        norm = colors.Normalize(vmin=vmin, vmax=vmax)

    _cmap = spedas_cmap if cmap == 'spedas' else cmap
    mesh  = ax.pcolormesh(T, E, Z, norm=norm, cmap=_cmap, shading='auto')

    if y_scale == 'log':
        ax.set_yscale('log')
    if labels:
        ax.set_xlabel('Time')
        ax.set_ylabel('Energy (eV)')
    if c_bar:
        cbar_label = (r'$\left[\frac{\text{keV}}{(\text{cm}^2 \text{s sr keV})}\right]$'
                      if labels else None)
        fig.colorbar(mesh, ax=ax, aspect=5, label=cbar_label)

    return fig, ax